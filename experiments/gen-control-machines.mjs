/**
 * Write packages/ui-components/src/controls/machines/index.js from the
 * `.lino` machines next to it (the test controls/machines.test.js checks
 * that they stay byte-equal).
 *
 *   node experiments/gen-control-machines.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { URL, fileURLToPath } from 'node:url';

const dir = fileURLToPath(
  new URL('../packages/ui-components/src/controls/machines/', import.meta.url)
);
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.lino'))
  .sort();
const entries = files.map((file) => {
  const text = readFileSync(join(dir, file), 'utf8');
  const kind = file.slice(0, -'.lino'.length);
  return `  '${kind}': \`${text.replace(/[`\\$]/g, '\\$&')}\`,`;
});
const out = `/**
 * The machines of the basic controls as text, by control kind, so they
 * load without a file system or a bundler. They are byte-equal to the
 * \`.lino\` files next to this module (generated by
 * experiments/gen-control-machines.mjs; tests/controls/machines.test.js
 * checks that they stay in sync).
 */

/** Machine text by control kind. */
export const CONTROL_MACHINES = Object.freeze({
${entries.join('\n')}
});
`;
writeFileSync(join(dir, 'index.js'), out);
console.log(`wrote ${files.length} machines`);
