#!/usr/bin/env node
// Render attribution text from the asset records in assets/assets.lino.
//
//   node scripts/render-attributions.mjs          # write assets/ATTRIBUTIONS.md
//   node scripts/render-attributions.mjs --check  # exit 1 when it is stale
//
// renderAttributions() is exported for later in-app use (markdown, html or
// lino output).

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  PUBLIC_DOMAIN_LICENSES,
  isOwnAsset,
  linoValue,
  parseAssetRecords,
  runCli,
  syncGeneratedFile,
} from './lib/asset-records.mjs';

export const ATTRIBUTIONS_PATH = 'assets/ATTRIBUTIONS.md';
const PUBLIC_DOMAIN = 'Public domain';

/** @param {import('./lib/asset-records.mjs').AssetRecord} record */
const isPublicDomain = (record) =>
  isOwnAsset(record) && PUBLIC_DOMAIN_LICENSES.includes(record.license ?? '');

const licenseUrl = (license) =>
  /^[A-Za-z0-9.+-]+$/.test(license)
    ? `https://spdx.org/licenses/${license.replace(/\+$/, '')}.html`
    : undefined;

/**
 * Group records by licence, public domain first, then by licence name.
 *
 * @param {import('./lib/asset-records.mjs').AssetRecord[]} records
 * @returns {[string, import('./lib/asset-records.mjs').AssetRecord[]][]}
 */
export function groupByLicense(records) {
  const groups = new Map();
  for (const record of records) {
    const key = isPublicDomain(record) ? PUBLIC_DOMAIN : (record.license ?? '');
    if (!groups.has(key)) {
      groups.set(key, []);
    }
    groups.get(key).push(record);
  }
  const rank = (key) => (key === PUBLIC_DOMAIN ? '' : key);
  return [...groups.entries()]
    .sort(([a], [b]) => rank(a).localeCompare(rank(b)))
    .map(([key, list]) => [
      key,
      [...list].sort((a, b) => a.id.localeCompare(b.id)),
    ]);
}

const escapeHtml = (text) =>
  String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const escapeMarkdown = (text) =>
  String(text).replace(/([\\`*_[\]<>|])/g, '\\$1');

function describe(record) {
  const own = isPublicDomain(record);
  return {
    copyright: own ? 'public domain' : record.copyright,
    licenseLink: record.notice ?? licenseUrl(record.license ?? ''),
    text: record.attributionText,
    own,
  };
}

const DEFAULT_GENERATOR =
  '`node scripts/render-attributions.mjs` from assets/assets.lino';

function renderMarkdown(
  records,
  { title = 'Asset attributions', generator = DEFAULT_GENERATOR } = {}
) {
  const lines = [
    `# ${title}`,
    '',
    `<!-- Generated by ${generator}. Do not edit by hand. -->`,
    '',
  ];
  if (records.length === 0) {
    lines.push('No assets are recorded.', '');
  }
  for (const [license, list] of groupByLicense(records)) {
    lines.push(`## ${escapeMarkdown(license)}`, '');
    for (const record of list) {
      const info = describe(record);
      const name = record.source
        ? `[${escapeMarkdown(record.id)}](${record.source})`
        : `**${escapeMarkdown(record.id)}**`;
      lines.push(
        `- ${name} (${record.kind}): ${record.files.map((f) => `\`${f}\``).join(', ')}`
      );
      lines.push(`  - Copyright: ${escapeMarkdown(info.copyright)}`);
      const licenseText = info.own
        ? `${record.license} (public domain)`
        : record.license;
      lines.push(
        `  - Licence: ${info.licenseLink ? `[${escapeMarkdown(licenseText)}](${info.licenseLink})` : escapeMarkdown(licenseText)}`
      );
      if (info.text) {
        lines.push(`  - Attribution: ${escapeMarkdown(info.text)}`);
      }
      if (record.modified === 'yes') {
        lines.push('  - Modified: yes');
      }
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function renderHtml(records) {
  const parts = [
    '<section class="attributions">',
    '<h2>Asset attributions</h2>',
  ];
  for (const [license, list] of groupByLicense(records)) {
    parts.push(`<h3>${escapeHtml(license)}</h3>`, '<ul>');
    for (const record of list) {
      const info = describe(record);
      const name = record.source
        ? `<a href="${escapeHtml(record.source)}">${escapeHtml(record.id)}</a>`
        : escapeHtml(record.id);
      const licenseName = escapeHtml(record.license);
      const licenseHtml = info.licenseLink
        ? `<a href="${escapeHtml(info.licenseLink)}">${licenseName}</a>`
        : licenseName;
      const text = info.text ? ` ${escapeHtml(info.text)}` : '';
      parts.push(
        `<li>${name}: ${escapeHtml(info.copyright)}, ${licenseHtml}.${text}</li>`
      );
    }
    parts.push('</ul>');
  }
  parts.push('</section>');
  return `${parts.join('\n')}\n`;
}

function renderLino(records) {
  const lines = [];
  for (const [license, list] of groupByLicense(records)) {
    for (const record of list) {
      const info = describe(record);
      const fields = [
        `(group ${linoValue(license)})`,
        `(copyright ${linoValue(info.copyright)})`,
        `(license ${linoValue(record.license ?? '')})`,
      ];
      if (record.source) {
        fields.push(`(source ${linoValue(record.source)})`);
      }
      if (info.licenseLink) {
        fields.push(`(notice ${linoValue(info.licenseLink)})`);
      }
      if (info.text) {
        fields.push(`(text ${linoValue(info.text)})`);
      }
      lines.push(`(${record.id}: attribution ${fields.join(' ')})`);
    }
  }
  return lines.length ? `${lines.join('\n')}\n` : '';
}

/**
 * @param {import('./lib/asset-records.mjs').AssetRecord[]} records
 * @param {{format?: 'markdown' | 'html' | 'lino', title?: string,
 *   generator?: string}} [options]  `title` and `generator` (the
 *   "Generated by" comment) apply to markdown
 * @returns {string}
 */
export function renderAttributions(
  records,
  { format = 'markdown', ...markdown } = {}
) {
  if (format === 'markdown') {
    return renderMarkdown(records, markdown);
  }
  if (format === 'html') {
    return renderHtml(records);
  }
  if (format === 'lino') {
    return renderLino(records);
  }
  throw new Error(`Unknown attribution format: ${format}`);
}

/**
 * @param {string} root
 * @param {{check?: boolean}} [options]
 * @returns {{stale: boolean}}
 */
export function updateAttributions(root, { check = false } = {}) {
  const text = readFileSync(join(root, 'assets/assets.lino'), 'utf8');
  const expected = renderAttributions(parseAssetRecords(text));
  return syncGeneratedFile(join(root, ATTRIBUTIONS_PATH), expected, {
    write: !check,
  });
}

function main(root, argv) {
  const check = argv.includes('--check');
  const { stale } = updateAttributions(root, { check });
  if (check && stale) {
    console.error(
      `::error::${ATTRIBUTIONS_PATH} is stale; run: node scripts/render-attributions.mjs`
    );
    return 1;
  }
  console.log(
    stale ? `Wrote ${ATTRIBUTIONS_PATH}` : `${ATTRIBUTIONS_PATH} is up to date.`
  );
  return 0;
}

runCli(import.meta.url, main);
